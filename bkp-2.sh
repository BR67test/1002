#!/bin/bash
# ============================================================
# SRV-BKP-02 — РЕЗЕРВНЫЙ BACKUP-СЕРВЕР (БАЗОВАЯ НАСТРОЙКА)
# ОС: ALT Server 10
# IP: 10.0.10.12/24, шлюз: 10.0.10.1
# ============================================================

set -e

echo "========================================="
echo "  НАСТРОЙКА SRV-BKP-02 (БАЗОВАЯ)"
echo "========================================="

# ----------------------------------------------------------
# 1. Обновление и пакеты
# ----------------------------------------------------------
echo "[1/4] Обновление и установка пакетов..."
apt-get update && apt-get dist-upgrade -y
apt-get install -y openssh-server chrony net-tools

# ----------------------------------------------------------
# 2. Сеть
# ----------------------------------------------------------
echo "[2/4] Настройка сети..."
mkdir -p /etc/net/ifaces/ens18

cat > /etc/net/ifaces/ens18/options << 'EOF'
TYPE=eth
BOOTPROTO=static
ONBOOT=yes
EOF

echo '10.0.10.12/24' > /etc/net/ifaces/ens18/ipv4address

mkdir -p /etc/net/ifaces/default
echo '10.0.10.1' > /etc/net/ifaces/default/ipv4route
echo "nameserver 10.0.10.10" > /etc/resolv.conf

systemctl restart network

echo ""
echo "=== Проверка связи ==="
ping -c 2 10.0.10.1

# ----------------------------------------------------------
# 3. Время
# ----------------------------------------------------------
echo "[3/4] Настройка времени..."
systemctl enable --now chronyd
sleep 2
chronyc makestep || true

# ----------------------------------------------------------
# 4. SSH
# ----------------------------------------------------------
echo "[4/4] Настройка SSH..."
systemctl enable --now sshd

# ----------------------------------------------------------
# Финал
# ----------------------------------------------------------
echo ""
echo "========================================="
echo "  SRV-BKP-02 ГОТОВ"
echo "========================================="
echo ""
echo "IP: 10.0.10.12"
echo "Шлюз: 10.0.10.1"
echo "DNS: 10.0.10.10"
