#!/bin/bash
# ============================================================
# Скрипт полной настройки коммутатора SW-01 (ЯДРО СЕТИ)
# ОС: ALT Linux 10 (JEOS)
# ens19 -> GW-01 (управление + транзит VLAN через OVS)
# ens20 -> Коммутатор серверного сегмента (trunk, VLAN 10, 20)
# ens21 -> Коммутатор пользовательского сегмента (trunk, VLAN 10, 20)
# ============================================================

set -e

echo "========================================="
echo "  НАСТРОЙКА SW-01 (КОММУТАТОР ЯДРА)"
echo "  ens19 -> GW-01 (IP: 10.0.0.2/24)"
echo "  ens20 -> Trunk (Серверный сегмент)"
echo "  ens21 -> Trunk (Пользовательский сегмент)"
echo "========================================="

# ----------------------------------------------------------
# 1. Обновление системы и установка пакетов
# ----------------------------------------------------------
echo "[1/4] Обновление системы и установка пакетов..."
apt-get update && apt-get dist-upgrade -y
apt-get install -y openvswitch tcpdump net-tools openssh-server chrony

# ----------------------------------------------------------
# 2. Настройка управления (ens19)
# ----------------------------------------------------------
echo "[2/4] Настройка интерфейса управления ens19..."

mkdir -p /etc/net/ifaces/ens19

cat > /etc/net/ifaces/ens19/options << 'EOF'
TYPE=eth
BOOTPROTO=static
ONBOOT=yes
EOF

cat > /etc/net/ifaces/ens19/ipv4address << 'EOF'
10.0.0.2/24
EOF

# Шлюз по умолчанию
mkdir -p /etc/net/ifaces/default
echo '10.0.0.1' > /etc/net/ifaces/default/ipv4route

# Применяем настройки сети
systemctl restart network

# ----------------------------------------------------------
# 3. Запуск Open vSwitch и настройка портов
# ----------------------------------------------------------
echo "[3/4] Запуск OVS и настройка транковых портов..."
systemctl enable --now openvswitch

# Создаём мост
ovs-vsctl add-br SW-BR0

# ens20 — линк к коммутатору серверного сегмента (trunk)
ovs-vsctl add-port SW-BR0 ens20 trunks=10,20

# ens21 — линк к коммутатору пользовательского сегмента (trunk)
ovs-vsctl add-port SW-BR0 ens21 trunks=10,20

# Добавляем ens19 в мост для транзита VLAN'ов
ovs-vsctl add-port SW-BR0 ens19 trunks=10,20

# Активируем интерфейсы
ip link set ens20 up
ip link set ens21 up
ip link set SW-BR0 up

# ----------------------------------------------------------
# 4. Синхронизация времени
# ----------------------------------------------------------
echo "[4/4] Настройка синхронизации времени..."
systemctl enable --now chronyd

# ----------------------------------------------------------
# Финал
# ----------------------------------------------------------
echo ""
echo "========================================="
echo "  НАСТРОЙКА SW-01 ЗАВЕРШЕНА"
echo "========================================="
echo ""
echo "Конфигурация OVS:"
ovs-vsctl show
echo ""
echo "Сетевые интерфейсы:"
ip -br a
echo ""
echo "Таблица маршрутизации:"
ip route
echo ""
echo "Проверка связи с GW-01:"
ping -c 4 10.0.0.1
