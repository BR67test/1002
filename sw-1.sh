#!/bin/bash
# ============================================================
# Скрипт полной настройки коммутатора SW-01 (ЯДРО СЕТИ)
# ОС: ALT Linux 10 (JEOS)
# Порты: ens19 -> GW-01 (trunk)
#        ens20 -> Коммутатор серверного сегмента (trunk, VLAN 10, 20)
#        ens21 -> Коммутатор пользовательского сегмента (trunk, VLAN 10, 20)
# Управление: mgmt -> 10.0.0.2/24 (внутренний интерфейс моста)
# ============================================================

set -e

echo "========================================="
echo "  НАСТРОЙКА SW-01 (Open vSwitch - ЯДРО)"
echo "  ens19 -> Trunk (GW-01)"
echo "  ens20 -> Trunk (Серверный сегмент)"
echo "  ens21 -> Trunk (Пользовательский сегмент)"
echo "  mgmt  -> 10.0.0.2/24 (Управление)"
echo "========================================="

# ----------------------------------------------------------
# 1. Обновление системы и установка Open vSwitch
# ----------------------------------------------------------
echo "[1/5] Обновление системы и установка openvswitch..."
apt-get update && apt-get dist-upgrade -y
apt-get install -y openvswitch tcpdump net-tools openssh-server

# ----------------------------------------------------------
# 2. Запуск Open vSwitch
# ----------------------------------------------------------
echo "[2/5] Запуск службы Open vSwitch..."
systemctl enable --now openvswitch

# ----------------------------------------------------------
# 3. Создание моста и настройка портов
# ----------------------------------------------------------
echo "[3/5] Создание моста SW-BR0 и настройка портов..."

# Создаём мост
ovs-vsctl add-br SW-BR0

# ens19 — линк от маршрутизатора (trunk, VLAN 10 и 20)
ovs-vsctl add-port SW-BR0 ens19 trunks=10,20

# ens20 — линк к коммутатору серверного сегмента (trunk, VLAN 10 и 20)
ovs-vsctl add-port SW-BR0 ens20 trunks=10,20

# ens21 — линк к коммутатору пользовательского сегмента (trunk, VLAN 10 и 20)
ovs-vsctl add-port SW-BR0 ens21 trunks=10,20

# Создаём внутренний интерфейс управления и назначаем IP
ovs-vsctl add-port SW-BR0 mgmt -- set Interface mgmt type=internal
ip addr add 10.0.0.2/24 dev mgmt
ip link set mgmt up

# ----------------------------------------------------------
# 4. Активация сетевых интерфейсов
# ----------------------------------------------------------
echo "[4/5] Активация сетевых интерфейсов..."
ip link set ens19 up
ip link set ens20 up
ip link set ens21 up
ip link set SW-BR0 up

# ----------------------------------------------------------
# 5. Сохранение конфигурации
# ----------------------------------------------------------
echo "[5/5] Сохранение конфигурации..."

# Сохраняем настройки интерфейса mgmt для автоподъёма после перезагрузки
mkdir -p /etc/net/ifaces/mgmt

cat > /etc/net/ifaces/mgmt/options << 'EOF'
BOOTPROTO=static
NM_CONTROLLED=no
DISABLED=no
CONFIG_IPV4=yes
ON_BOOT=yes
EOF

echo '10.0.0.2/24' > /etc/net/ifaces/mgmt/ipv4address

# Настройка шлюза по умолчанию для управления
mkdir -p /etc/net/ifaces/default
echo '10.0.0.1' > /etc/net/ifaces/default/ipv4route

# Перезапуск сети для применения сохранённых настроек (безопаснее, чем ручной ip addr)
systemctl restart network

# ----------------------------------------------------------
# Финал
# ----------------------------------------------------------
echo ""
echo "========================================="
echo "  НАСТРОЙКА SW-01 ЗАВЕРШЕНА"
echo "========================================="
echo ""
echo "Конфигурация OVS:"
ovs-vsctl show
echo ""
echo "Сетевые интерфейсы:"
ip -br a | grep -E "ens19|ens20|ens21|mgmt|SW-BR0"
echo ""
echo "Таблица маршрутизации:"
ip route
echo ""
echo "Проверка доступности GW-01:"
ping -c 2 10.0.0.1 || echo "ВНИМАНИЕ: GW-01 недоступен, проверьте сеть"
