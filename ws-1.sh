#!/bin/bash
# ============================================================
# WS-01 — РАБОЧАЯ СТАНЦИЯ ПОЛЬЗОВАТЕЛЯ
# ОС: РЕД ОС
# IP: 10.0.20.21/24, шлюз: 10.0.20.1, DNS: 10.0.10.10
# ============================================================

set -e

echo "========================================="
echo "  НАСТРОЙКА WS-01 (РЕД ОС)"
echo "========================================="

# ----------------------------------------------------------
# 1. Обновление и пакеты
# ----------------------------------------------------------
echo "[1/3] Обновление и установка пакетов..."
apt-get update && apt-get dist-upgrade -y
apt-get install -y chrony net-tools openssh-server

# ----------------------------------------------------------
# 2. Сеть
# ----------------------------------------------------------
echo "[2/3] Настройка сети..."
mkdir -p /etc/net/ifaces/ens18

cat > /etc/net/ifaces/ens18/options << 'EOF'
TYPE=eth
BOOTPROTO=static
ONBOOT=yes
EOF

echo '10.0.20.21/24' > /etc/net/ifaces/ens18/ipv4address

mkdir -p /etc/net/ifaces/default
echo '10.0.20.1' > /etc/net/ifaces/default/ipv4route
echo "nameserver 10.0.10.10" > /etc/resolv.conf

systemctl restart network

echo ""
echo "=== Проверка связи ==="
ping -c 2 10.0.20.1

# ----------------------------------------------------------
# 3. Время
# ----------------------------------------------------------
echo "[3/3] Настройка времени..."
systemctl enable --now chronyd
sleep 2
chronyc makestep || true

# ----------------------------------------------------------
# Финал
# ----------------------------------------------------------
echo ""
echo "========================================="
echo "  WS-01 ГОТОВА"
echo "========================================="
echo ""
echo "IP: 10.0.20.21"
echo "Шлюз: 10.0.20.1"
echo "DNS: 10.0.10.10"
